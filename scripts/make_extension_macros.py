"""Write the value file the v3 manuscript reads every extension number from (gate G5-ext).

Two key families, both read through the same \\val command as the locked value file:

  ext/<path>  the quantity at <path> in llm_ext_analysis.json
  add/<path>  the quantity at <path> in the added model's locked-design analysis
              (llm_added/llm_analysis_v3.json), formatted exactly as the locked value file
              formats the same path for the four locked models

The added model's own H1 to H5 tests are not written: their Holm adjustment runs over that one
model alone, and the confirmatory tests for the added model are R1 to R5 in the extension family.

Formatting follows the locked rules (make_llm_macros.format_value). Exact (Clopper-Pearson) bounds
and the Youden J print as percentages, as Wilson bounds do; the two extension loss blocks print as
the locked loss block does. In ext/loss_f2 the world named "attacked" is the payload-family-2
attacked world: the locked loss code reads only the locked world names.

Only an OFFICIAL extension analysis whose G4-ext passed, with an OFFICIAL added analysis that passed
G4 when a model was added, may write llm_ext_values.tex. Anything else writes
SMOKE_llm_ext_values.tex, which the manuscript never inputs.

  python3 make_extension_macros.py                                   # official analyses, official file
  python3 make_extension_macros.py --analysis <SMOKE json>           # writes SMOKE_llm_ext_values.tex
  python3 make_extension_macros.py --check paper_v3.tex results.tex  # G5 over both value files
"""
from __future__ import annotations
import sys as _sys
from pathlib import Path as _Path
for _d in ('src', 'experiments', 'scripts'):
    _p = str(_Path(__file__).resolve().parents[1] / _d)
    if _p not in _sys.path:
        _sys.path.insert(0, _p)

import argparse
import json
import logging
import sys
from pathlib import Path
from typing import Any, Iterable, Mapping

import make_triage_macros as locked

logger = logging.getLogger(__name__)

PAPER_ROOT = locked.PAPER_ROOT
DEFAULT_ANALYSIS = PAPER_ROOT / "results/triage_extension/extension_study_analysis.json"
DEFAULT_ADDED = PAPER_ROOT / "results/triage_added/triage_study_analysis.json"
DEFAULT_OUTPUT_DIR = locked.DEFAULT_OUTPUT_DIR
EXT_PERCENT_BASES = locked.PERCENT_BASES | {"exact", "youden_j"}
EXT_SKIPPED_TOP_LEVEL = {"inputs", "label", "g4_passed", "models", "added_model", "policies", "hypotheses"}
LOSS_BLOCKS = {"loss_extended", "loss_f2"}
IDENTIFIER_LEAVES = {"bootstrap_seed", "extension_seed"}  # integers that name, not count: never grouped
Key = locked.Key


def ext_kind(path: Key) -> str:
    """Kind of an extension leaf; path excludes the ext/ prefix."""
    leaf = path[-2] if path[-1] in {"lo", "hi"} else path[-1]
    base = leaf[:-2] if leaf.endswith("95") else leaf
    if base in locked.P_BASES:
        return "p"
    if base in EXT_PERCENT_BASES:
        return "pct"
    if path[0] in LOSS_BLOCKS:
        return "kstar" if base == "k_star" else "loss"
    if base in locked.ONE_DECIMAL_BASES:
        return "one"
    return "three"


def ext_format(path: Key, value: Any) -> str | None:
    """TeX text for one extension leaf; the locked rules with ext_kind in place of the locked kind."""
    if value is None or isinstance(value, (bool, str)) or not isinstance(value, (int, float)):
        return locked.format_value(path, value)
    if path[-1] in IDENTIFIER_LEAVES and isinstance(value, int):
        return str(value)
    kind = ext_kind(path)
    if kind == "pct":
        return locked._signed(100.0 * value, 1)
    if kind == "p":
        return "\\ensuremath{<}0.001" if value < 0.001 else f"{value:.3f}"
    if kind in {"loss", "three"} and isinstance(value, int):
        return locked._grouped(value)
    if kind in {"kstar", "one"}:
        return locked._signed(float(value), 1)
    return locked._signed(float(value), 3)


def ext_values(analysis: Mapping[str, Any]) -> dict[Key, str]:
    raw: dict[Key, Any] = {}
    for key, value in analysis.items():
        if key not in EXT_SKIPPED_TOP_LEVEL:
            locked.flatten(value, (key,), raw)
    return {("ext",) + path: text for path, value in raw.items() if (text := ext_format(path, value)) is not None}


def added_values(analysis: Mapping[str, Any]) -> dict[Key, str]:
    raw = locked.analysis_values(analysis)
    out: dict[Key, str] = {}
    for path, value in raw.items():
        if path[0] == "salad" and len(path) > 2 and path[2] == "tests":
            continue
        text = locked.format_value(path, value)
        if text is not None:
            out[("add",) + path] = text
    return out


def render(values: Mapping[Key, str], official: bool, label: str, sources: Iterable[Path]) -> str:
    lines = [
        "% Generated by scripts/make_extension_macros.py. Do not edit; regenerate.",
        f"% Extension analysis label: {label}",
        *(f"% source {locked._shown(path)} sha256 {locked._sha256(path)}" for path in sources),
        locked.GUARD,
        f"\\def\\llmextvaluesource{{{'OFFICIAL' if official else 'SMOKE'}}}",
    ]
    for path in sorted(values):
        lines.append(f"\\expandafter\\def\\csname llmv@{locked._validate_key(path)}\\endcsname{{{values[path]}}}")
    return "\n".join(lines) + "\n"


def is_official(analysis: Mapping[str, Any]) -> bool:
    return analysis.get("label") == "OFFICIAL" and bool(analysis.get("g4_passed"))


def check(files: list[Path], value_files: list[Path], report: Path | None) -> int:
    defined: set[str] = set()
    for path in value_files:
        defined |= locked._defined_keys(path)
    result = locked.check_manuscript(files, defined)
    result["values_files"] = [locked._shown(path) for path in value_files]
    if report:
        report.write_text(json.dumps(result, indent=2) + "\n", encoding="utf-8")
    logger.info("G5 %s: %d keys used, %d missing, %d bare numbers to review", "PASS" if result["passed"] else "FAIL",
                result["keys_used"], len(result["missing_keys"]), len(result["bare_numbers"]))
    for key in result["missing_keys"]:
        logger.error("undefined key %s", key)
    return 0 if result["passed"] else 1


def main() -> int:
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(message)s")
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--analysis", type=Path, default=DEFAULT_ANALYSIS)
    parser.add_argument("--added-analysis", type=Path, default=DEFAULT_ADDED)
    parser.add_argument("--output-dir", type=Path, default=DEFAULT_OUTPUT_DIR)
    parser.add_argument("--check", type=Path, nargs="+", help="manuscript files to check against both value files")
    parser.add_argument("--values", type=Path, nargs="+", help="value files for --check (default: the official two)")
    parser.add_argument("--report", type=Path, help="write the --check result as JSON here")
    args = parser.parse_args()

    if args.check:
        value_files = args.values or [args.output_dir / "llm_values.tex", args.output_dir / "llm_ext_values.tex"]
        return check(args.check, [path.resolve() for path in value_files], args.report)

    analysis = json.loads(args.analysis.read_text(encoding="utf-8"))
    added_model = analysis.get("added_model")
    added = json.loads(args.added_analysis.read_text(encoding="utf-8")) if added_model else None
    official = analysis.get("label") == "OFFICIAL"
    if official and not is_official(analysis):
        logger.error("refusing to write values: the OFFICIAL extension analysis did not pass G4-ext")
        return 1
    if official and added_model and not (added and is_official(added) and added.get("models") == [added_model]):
        logger.error("refusing to write values: no OFFICIAL, G4-passed locked-design analysis of %s", added_model)
        return 1
    values = ext_values(analysis)
    if added:
        values.update(added_values(added))
    sources = [args.analysis.resolve()] + ([args.added_analysis.resolve()] if added else [])
    text = render(values, official, str(analysis.get("label", "")), sources)
    args.output_dir.mkdir(parents=True, exist_ok=True)
    output = args.output_dir / (("" if official else "SMOKE_") + "llm_ext_values.tex")
    output.write_text(text, encoding="utf-8")
    logger.info("wrote %d values to %s (%s)", len(values), output, "OFFICIAL" if official else "SMOKE")
    return 0


if __name__ == "__main__":
    sys.exit(main())
